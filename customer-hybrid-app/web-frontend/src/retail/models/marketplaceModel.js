export function calculateCartTotals(cart) {
  if (!cart || !cart.items) {
    return { totalCount: 0, totalAmount: 0 };
  }
  const items = Object.values(cart.items);
  const totalCount = items.reduce((acc, item) => acc + (item.qty || 0), 0);
  const totalAmount = items.reduce((acc, item) => acc + ((item.product?.price || 0) * (item.qty || 0)), 0);
  return { totalCount, totalAmount };
}

export function getStoreById(storeId) {
  if (!storeId) return VERIFIED_STORES[1]; // Default to BuildWell Traders
  const matched = VERIFIED_STORES.find((s) => s.id === storeId);
  return matched || VERIFIED_STORES[1];
}

